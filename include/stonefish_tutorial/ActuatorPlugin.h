#pragma once

#include <Stonefish/actuators/LinkActuator.h>
#include <stonefish_ros2/ROS2ActuatorPluginInterface.h>
#include "std_msgs/msg/float64.hpp"

namespace sf
{
    //! A class representing an example of a sensor plugin that measures the surrounding fluid velocity.
    class ActuatorPlugin : public LinkActuator, public ROS2ActuatorPluginInterface
    {
    public:
        //! A constructor.
        /*!
         \param uniqueName a name for the actuator
         \param amplitude the amplitude of the sine wave signal generated by the actuator [1]
         \param frequency the frequency of the sine wave signal generated by the actuator [Hz]
         */
        ActuatorPlugin(std::string_view uniqueName, Scalar amplitude, Scalar frequency);

        //! A method used to update the internal state of the actuator.
        /*!
         \param dt a time step of the simulation [s]
         */
        void Update(Scalar dt) override;

        //! A method for creating ROS2 publishers for the actuator plugin.
        /*!
         \param nh a shared pointer to the ROS2 node handle
         \param pubs a map to store the created publishers, with actuator names as keys
         \param pubTopics a map storing all parsed publisher topics
         */
        void CreatePublishers(const std::shared_ptr<rclcpp::Node>& nh, 
            std::unordered_map<std::string, rclcpp::PublisherBase::SharedPtr>& pubs, 
            std::unordered_map<std::string, std::string>& pubTopics) const override;

        //! A method for publishing actuator data.
        /*!
         \param nh a shared pointer to the ROS2 node handle
         \param pubs a map of the available publishers, with actuator names as keys
         */
        void Publish(const std::shared_ptr<rclcpp::Node>& nh, 
            std::unordered_map<std::string, rclcpp::PublisherBase::SharedPtr>& pubs) const override;

        //! A method for creating ROS2 actuators for the actuator plugin.
        /*!
         \param nh a shared pointer to the ROS2 node handle
         \param subs a map to store the created subscribers, with actuator names as keys
         \param subTopics a map storing all parsed subscriber topics
         */
        void CreateSubscribers(const std::shared_ptr<rclcpp::Node>& nh, 
            std::unordered_map<std::string, rclcpp::SubscriptionBase::SharedPtr>& subs, 
            std::unordered_map<std::string, std::string>& subTopics) override;

        //! A callback for subscribing to new amplitude setpoint.
        /*!
         \param msg a shared pointer to a message structure
         */
        void Callback(const std_msgs::msg::Float64::SharedPtr msg);

        //! A method returning the type of link actuator.
        LinkActuatorType GetLinkActuatorType() const override;

        //! A method returning the construction info for the actuator.
        static ConstructInfo GetConstructInfo();

        //! A method constructing the actuator based on info structure.
        /*!
         \param uniqueName a name for the actuator
         \param info a construction info structure
        */
        static ActuatorPlugin* Construct(std::string_view uniqueName, ConstructInfo* info);

    private:
        Scalar amplitude_;
        Scalar frequency_;
        Scalar time_;
    };
}